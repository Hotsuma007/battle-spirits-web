const patterns = Object.entries(translations).filter(([source]) => /\{\d+\}/.test(source)).map(([source, translation]) => {
  const escaped = source.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const expression = escaped.replace(/\\\{\d+\\\}/g, "(.+?)");
  return { pattern: new RegExp(`^${expression}$`), translation };
});
const colors = { red: "赤", purple: "紫", green: "緑", white: "白", yellow: "黄", blue: "青" };

export function japaneseGameError(error) {
  const value = String(error || "");
  if (!value) return "";
  if (translations[value]) return translations[value];
  for (const { pattern, translation } of patterns) {
    const match = value.match(pattern);
    if (match) return translation.replace(/\{(\d+)\}/g, (_, index) => colors[String(match[Number(index) + 1]).toLowerCase()] || match[Number(index) + 1]);
  }
  return value;
}
